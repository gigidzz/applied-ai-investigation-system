"""Generate the synthetic operations corpus and its design document.

Produces documents in six formats under data/corpus/ops/, plus:

    DESIGN.md       every planted contradiction, gap and near-duplicate,
                    naming the documents involved and what a correct system
                    should do about each one
    MANIFEST.json   counts per format and the generator seed

Everything is derived from scripts/ops_corpus/facts.py, so regenerating
produces identical files. That matters because the evaluation set is labelled
against these documents by path.

Usage:
    uv run python scripts/build_ops_corpus.py
"""

from __future__ import annotations

import hashlib
import json
import shutil
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from ops_corpus import facts, renderers  # noqa: E402

from ragsys.config import settings  # noqa: E402
from ragsys.logging import get_logger, setup_logging  # noqa: E402

log = get_logger("scripts.build_ops_corpus")

SUBDIRS = ("incidents", "changes", "runbooks", "services", "adr", "threads", "reports")


def prepare(root: Path) -> None:
    """Start from an empty tree so removed documents do not linger."""
    if root.exists():
        shutil.rmtree(root)
    for name in SUBDIRS:
        (root / name).mkdir(parents=True, exist_ok=True)


def render_all(root: Path) -> list[Path]:
    written: list[Path] = []

    incidents = facts.build_incidents()
    for incident in incidents:
        path = root / "incidents" / f"{incident.incident_id}.pdf"
        renderers.write_incident_pdf(incident, path)
        written.append(path)
    log.info("wrote %d incident post-mortems (pdf)", len(incidents))

    deploys = facts.build_deploys()
    change_log = root / "changes" / "change-log.csv"
    renderers.write_change_log_csv(deploys, change_log)
    written.append(change_log)
    log.info("wrote change log with %d rows (csv)", len(deploys))

    runbooks = facts.build_runbooks()
    for runbook in runbooks:
        path = root / "runbooks" / f"{runbook.slug}.md"
        renderers.write_runbook_md(runbook, path)
        written.append(path)
    log.info("wrote %d runbooks (md)", len(runbooks))

    for service in facts.SERVICES:
        path = root / "services" / f"{service.name}.json"
        renderers.write_service_json(service, facts.SERVICES, path)
        written.append(path)
    log.info("wrote %d service catalogue entries (json)", len(facts.SERVICES))

    for adr in facts.ADRS:
        path = root / "adr" / f"{adr.adr_id}.docx"
        renderers.write_adr_docx(adr, path)
        written.append(path)
    log.info("wrote %d architecture decision records (docx)", len(facts.ADRS))

    threads = facts.build_threads()
    for thread in threads:
        path = root / "threads" / f"{thread.thread_id}.txt"
        renderers.write_thread_txt(thread, path)
        written.append(path)
    log.info("wrote %d chat threads (txt)", len(threads))

    for report in facts.OPS_REPORTS:
        path = root / "reports" / f"{report.slug}.md"
        renderers.write_ops_report_md(report, path)
        written.append(path)
    log.info("wrote %d operations reports (md)", len(facts.OPS_REPORTS))

    # near-duplicate N2: one incident restated in a second format
    duplicated = next(i for i in incidents if i.incident_id == "INC-2026-01-22")
    summary = root / "reports" / f"summary-{duplicated.incident_id}.md"
    renderers.write_incident_summary_md(duplicated, summary)
    written.append(summary)
    log.info("wrote 1 cross-format duplicate summary (md)")

    return written


def write_design_doc(root: Path, written: list[Path]) -> None:
    by_kind: dict[str, list[facts.Planted]] = {}
    for planted in facts.PLANTED:
        by_kind.setdefault(planted.kind, []).append(planted)

    titles = {
        "multi_hop": "Multi-document questions",
        "contradiction": "Planted contradictions",
        "gap": "Deliberate gaps",
        "near_duplicate": "Near-duplicates",
    }

    lines = [
        "# Operations corpus design",
        "",
        f"A synthetic corpus for the fictional company {facts.COMPANY}, generated by",
        "`scripts/build_ops_corpus.py` from `scripts/ops_corpus/facts.py`.",
        "",
        "Its purpose is to test the three behaviours the HotpotQA corpus cannot:",
        "reasoning across documents of different formats, detecting sources that",
        "contradict each other, and declining to answer when the corpus does not",
        "contain the answer. Wikipedia does not contradict itself on purpose and",
        "never omits an answer deliberately, so those cases are constructed here.",
        "",
        "Everything below is planted on purpose. This file is the answer key.",
        "",
    ]

    for kind in ("multi_hop", "contradiction", "gap", "near_duplicate"):
        items = by_kind.get(kind, [])
        if not items:
            continue
        lines += [f"## {titles[kind]}", ""]
        for planted in items:
            lines += [
                f"### {planted.label}",
                "",
                planted.explanation,
                "",
                "**Documents involved**",
                "",
            ]
            lines += [f"- `{document}`" for document in planted.documents]
            lines += [
                "",
                f"**Probe question** — {planted.probe_question}",
                "",
                f"**Expected behaviour** — {planted.expected_behaviour}",
                "",
            ]

    counts = Counter(path.suffix.lstrip(".") for path in written)
    lines += [
        "## Inventory",
        "",
        "| Format | Documents |",
        "|---|---|",
    ]
    for suffix, count in sorted(counts.items()):
        lines += [f"| `.{suffix}` | {count} |"]
    lines += [
        f"| **total** | **{len(written)}** |",
        "",
        "## Reproducibility",
        "",
        f"All variation derives from seed `{facts.SEED}`. PDF and DOCX creation",
        "timestamps are pinned, so regenerating the corpus produces byte-identical",
        "files and the evaluation labels in this document stay valid.",
        "",
    ]

    (root / "DESIGN.md").write_text("\n".join(lines), encoding="utf-8")


def write_manifest(root: Path, written: list[Path]) -> dict:
    counts = Counter(path.suffix.lstrip(".") for path in written)
    digest = hashlib.sha256()
    for path in sorted(written):
        digest.update(path.name.encode("utf-8"))
        digest.update(path.read_bytes())

    manifest = {
        "company": facts.COMPANY,
        "seed": facts.SEED,
        "documents": len(written),
        "by_format": dict(sorted(counts.items())),
        "bytes": sum(path.stat().st_size for path in written),
        "corpus_fingerprint": digest.hexdigest()[:32],
        "planted": {
            "contradictions": sum(1 for p in facts.PLANTED if p.kind == "contradiction"),
            "gaps": sum(1 for p in facts.PLANTED if p.kind == "gap"),
            "near_duplicates": sum(1 for p in facts.PLANTED if p.kind == "near_duplicate"),
            "multi_hop_scenarios": sum(1 for p in facts.PLANTED if p.kind == "multi_hop"),
        },
    }
    (root / "MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


def write_eval_questions(root: Path) -> int:
    """Write the labelled question set for the operations corpus.

    Two sources. The planted challenges in facts.PLANTED contribute the
    contradiction, unanswerable and cross-document cases, each already carrying
    its expected behaviour. Simple single-fact questions are derived from the
    service catalogue and incident records, because HotpotQA supplies no simple
    questions at all — every one of its validation questions is multi-hop and
    labelled 'hard'.

    Written to data/eval/ops_questions.jsonl, alongside the HotpotQA questions.
    """
    rows: list[dict] = []

    for planted in facts.PLANTED:
        rows.append(
            {
                "question_id": planted.label.split(" ")[0],
                "question": planted.probe_question,
                "answer": planted.answer,
                "category": planted.category or planted.kind,
                "expected_behaviour": planted.expected_behaviour,
                "gold_documents": list(planted.gold_documents or planted.documents),
                "source": "ops/planted",
            }
        )

    incidents = facts.build_incidents()

    for service in facts.SERVICES[:6]:
        rows.append(
            {
                "question_id": f"S-team-{service.name}",
                "question": f"Which team owns {service.name}?",
                "answer": service.team,
                "category": "simple",
                "expected_behaviour": (
                    f"Answer '{service.team}', citing the service catalogue entry."
                ),
                "gold_documents": [f"services/{service.name}.json"],
                "source": "ops/derived",
            }
        )

    for incident in incidents[1:6]:
        rows.append(
            {
                "question_id": f"S-cause-{incident.incident_id}",
                "question": f"What was the root cause of {incident.incident_id}?",
                "answer": incident.root_cause,
                "category": "simple",
                "expected_behaviour": (
                    f"Summarise the root cause and cite incidents/{incident.incident_id}.pdf."
                ),
                "gold_documents": [f"incidents/{incident.incident_id}.pdf"],
                "source": "ops/derived",
            }
        )

    flagship = incidents[0]
    rows.append(
        {
            "question_id": "X-downstream",
            "question": (
                "Which services were affected downstream when payment-gateway "
                "failed in March, and why were they affected?"
            ),
            "answer": ", ".join(flagship.affected_services),
            "category": "cross_document_synthesis",
            "expected_behaviour": (
                "Name checkout-api and merchant-portal, and explain that both "
                "declare payment-gateway as a dependency in the service "
                "catalogue. Requires joining the incident report to the "
                "catalogue."
            ),
            "gold_documents": [
                f"incidents/{flagship.incident_id}.pdf",
                "services/checkout-api.json",
                "services/merchant-portal.json",
            ],
            "source": "ops/derived",
        }
    )
    rows.append(
        {
            "question_id": "X-policy-violation",
            "question": (
                "Did the March connection pool change violate documented "
                "guidance, and where is that guidance written?"
            ),
            "answer": (
                "Yes. The runbook sets a minimum pool size of 25 and the release reduced it to 10."
            ),
            "category": "cross_document_synthesis",
            "expected_behaviour": (
                "Compare the change log entry for pay-gw-4.2.1 against the "
                "pool-sizing section of the payment-gateway runbook, and cite "
                "both."
            ),
            "gold_documents": [
                "changes/change-log.csv",
                "runbooks/runbook-payment-gateway-v2.md",
            ],
            "source": "ops/derived",
        }
    )

    out = settings.eval_dir / "ops_questions.jsonl"
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")

    counts = Counter(row["category"] for row in rows)
    log.info("wrote %d evaluation questions: %s", len(rows), dict(counts))
    return len(rows)


def main() -> int:
    setup_logging()
    root = settings.corpus_dir / "ops"
    prepare(root)
    written = render_all(root)
    write_design_doc(root, written)
    question_count = write_eval_questions(root)
    manifest = write_manifest(root, written)
    manifest["eval_questions"] = question_count
    log.info("corpus written to %s", root)
    print("\n" + json.dumps(manifest, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
